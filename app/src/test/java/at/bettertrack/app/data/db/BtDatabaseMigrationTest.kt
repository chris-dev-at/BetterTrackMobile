    /**
     * A migration that exists but is never registered is a migration that does
     * not run; a gap in the chain is a hard `IllegalStateException` at open.
     */
    @Test
    fun theRegisteredChainIsUnbrokenFromOneToTheDeclaredVersion() {
        // `@Database` has CLASS retention, so the schema version is read where it
        // actually matters at runtime: off the generated open delegate.
        val declared = roomOpenDelegate().let { delegate ->
            delegate.javaClass.getMethod("getVersion").apply { isAccessible = true }.invoke(delegate) as Int
        }
        val steps = BtDatabase.MIGRATIONS.map { it.startVersion to it.endVersion }.sortedBy { it.first }

        assertEquals("every migration must advance exactly one version", emptyList<Pair<Int, Int>>(), steps.filter { it.second != it.first + 1 })
        assertEquals("no duplicate start versions", steps.size, steps.map { it.first }.toSet().size)
        assertEquals("chain must start at 1", 1, steps.first().first)
        assertEquals("chain must end at the declared @Database version", declared, steps.last().second)
        assertEquals("chain must have no gaps", (1 until declared).toList(), steps.map { it.first })
    }

    /**
     * Cross-check on the git archaeology: the v7 schema reconstructed from the
     * entity definitions at rev `4b24c6c` must be the schema the owner's phone
     * actually holds. If these ever disagree, the reconstructions the rest of
     * this file relies on are fiction.
     */
    @Test
    fun reconstructedV7MatchesTheOwnersDevice() {
        val real = schemaFrom(SCHEMA_V7_OWNER_DEVICE)
        val reconstructed = schemaFrom(SCHEMA_V7)
        assertEquals("tables", real.keys.sorted(), reconstructed.keys.sorted())
        // Compared with Room's rules, not byte-for-byte: his `custom_assets` was
        // CREATEd at v4 while the reconstruction ALTERs into v4, so the table
        // carries `DEFAULT 0` on `smoothing` in one and not the other. Room reads
        // both as the same schema, and it is Room's opinion that decides whether
        // an app opens.
        assertEquals("reconstructed v7 differs from the device", emptyList<String>(), diffSchemas(real, reconstructed))
    }

    // ── The exported schema JSONs (app/schemas), now that they exist ─────────
    //
    // `exportSchema` was `false` for eleven versions — a long-flagged defect,
    // because the export is what makes a migration reviewable and what lets a
    // test start from the schema that ACTUALLY shipped rather than from a
    // reconstruction of it. It is on from v11 forward: 11.json was exported
    // before the v12 work, 12.json with it, and both are committed.

    /** Every committed export must be a schema this code still agrees with. */
    @Test
    fun theCommittedSchemaExportsMatchTheRoomExpectation() {
        val declared = declaredVersion()
        assertEquals("the newest export must be the declared version", declared, exportedVersions().max())
        assertTrue("v11 must stay exported as the migration's starting point", 11 in exportedVersions())

        val expected = openJdbc(newDbFile()).use { conn ->
            createRoomExpectedTables(conn)
            readSchema(conn)
        }
        val exported = schemaFrom(exportedStatements(declared))
        assertEquals(
            "schemas/$declared.json differs from what Room's compiler generates — re-export it",
            emptyList<String>(),
            diffSchemas(expected, exported),
        )
        assertEquals("tables", expected.keys.sorted(), exported.keys.sorted())
    }

    /**
     * The v11→v12 step, started from the COMMITTED v11 export rather than from a
     * reconstruction: this is the closest a JVM test gets to `MigrationTestHelper`
     * (which needs an instrumented device, and this project's whole migration
     * suite is deliberately device-free so CI gates on it).
     *
     * `runMigrations` runs the whole registered chain from 11, so the database it
