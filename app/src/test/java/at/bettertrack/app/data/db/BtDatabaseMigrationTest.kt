/**
 * The migration chain, executed for real.
 *
 * Every other guarantee in this app is worth nothing if the database will not
 * open: [BtDatabase] deliberately has no `fallbackToDestructiveMigration()`
 * (the outbound queue is durable user data, §7.3), so a migration that does not
 * reproduce the schema Room's compiler expects does not degrade — it throws from
 * `validateMigration` inside the open transaction, which Room then repeats, and
 * fails identically, on every single launch. That is a crash loop whose only
 * user-visible escape is clearing app data, i.e. destroying the very queue the
 * no-fallback policy exists to protect.
 *
 * ## How this test gets its two sides
 *
 * **Expected** comes from the KSP-generated `BtDatabase_Impl`, not from a copy of
 * it: the test reflects the real `createAllTables` onto a scratch database. That
 * is byte-for-byte the shape `validateMigration` compares against, and it moves
 * automatically the moment an `@Entity` changes — a hand-maintained expectation
 * would just be a second thing to forget to update.
 *
 * **Actual** comes from building a database at a historical version and running
 * [BtDatabase.MIGRATIONS] — the same array [BtDatabase.create] registers — over
 * it. Real SQLite (sqlite-jdbc), real migration objects, real SQL.
 *
 * The comparison replicates Room's own `TableInfo` rules rather than diffing DDL
 * text: type AFFINITY (not the spelling), `NOT NULL`, primary-key position, the
 * default value only where the entity itself declares one, and the `index_`-
 * prefixed indices with their uniqueness and column order. Anything Room would
 * reject, this rejects; anything Room tolerates (column order, extra tables it
 * does not know about), this tolerates.
 *
 * ## Why the historical schemas are spelled out here
 *
 * They are written as literal SQL, each labelled with the git rev it was read
 * from, instead of being generated by replaying our own migrations. Replaying
 * the migrations to build the starting point would only prove the chain is
 * self-consistent; pinning the historical shapes independently is what lets this
 * test notice that the chain has drifted away from what shipped.
 *
 * [SCHEMA_V7_OWNER_DEVICE] is not a reconstruction at all — it is the `.schema`
 * of the owner's actual phone database, pulled over adb on 2026-08-05 while it
 * sat at `user_version = 7`. Only the shape is here; none of his rows are.
 *
 * From v11 on there is a third, better source: `exportSchema` is finally ON and
 * `app/schemas/at.bettertrack.app.data.db.BtDatabase/<version>.json` is
 * committed, so the newest steps start from the schema Room itself wrote rather
 * than from anybody's transcription of it. `MigrationTestHelper` — the androidx
 * way to consume those files — needs an instrumented device; this suite stays
 * device-free on purpose (it is a CI gate), so it consumes the same JSONs
 * through the same JDBC harness instead.
 */
class BtDatabaseMigrationTest {

