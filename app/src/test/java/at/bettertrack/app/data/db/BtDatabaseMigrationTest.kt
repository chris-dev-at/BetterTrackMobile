    private fun declaredVersion(): Int = roomOpenDelegate().let { delegate ->
        delegate.javaClass.getMethod("getVersion").apply { isAccessible = true }.invoke(delegate) as Int
    }

    private fun exportedSchemaDir(): File =
        listOf(File("schemas"), File("app/schemas")).firstOrNull { it.isDirectory }
            ?.resolve("at.bettertrack.app.data.db.BtDatabase")
            ?.takeIf { it.isDirectory }
            ?: error("exported Room schemas not found from ${File(".").absolutePath}")

    private fun exportedVersions(): List<Int> =
        exportedSchemaDir().listFiles().orEmpty()
            .mapNotNull { it.name.removeSuffix(".json").toIntOrNull() }
            .sorted()

    /** The `CREATE` statements Room itself wrote into `<version>.json`. */
    private fun exportedStatements(version: Int): List<String> {
        val file = exportedSchemaDir().resolve("$version.json")
        assertTrue("missing exported schema ${file.absolutePath}", file.isFile)
        val database = Json.parseToJsonElement(file.readText()).jsonObject["database"]!!.jsonObject
        return buildList {
            database["entities"]!!.jsonArray.forEach { entity ->
                val table = entity.jsonObject["tableName"]!!.jsonPrimitive.content
                fun sql(element: kotlinx.serialization.json.JsonElement) =
                    element.jsonObject["createSql"]!!.jsonPrimitive.content.replace("\${TABLE_NAME}", table)
                add(sql(entity))
                entity.jsonObject["indices"]?.jsonArray?.forEach { add(sql(it)) }
            }
        }
    }

    // ── Machinery ────────────────────────────────────────────────────────────

    private fun withMigratedDb(schema: List<String>, fromVersion: Int, assertions: (Connection) -> Unit) {
        openJdbc(newDbFile()).use { conn ->
            conn.applyAll(schema)
            conn.exec("PRAGMA user_version = $fromVersion")
            runMigrations(conn, from = fromVersion)
            assertions(conn)
        }
    }

    /** Runs the REAL [BtDatabase.MIGRATIONS] objects, in Room's own order. */
    private fun runMigrations(conn: Connection, from: Int) {
        val db = jdbcSupportDatabase(conn)
        BtDatabase.MIGRATIONS
            .filter { it.startVersion >= from }
            .sortedBy { it.startVersion }
            .forEach { migration ->
                check(migration.startVersion == conn.userVersion()) {
                    "chain broke: at v${conn.userVersion()} but next migration starts at ${migration.startVersion}"
                }
                migration.migrate(db)
                conn.exec("PRAGMA user_version = ${migration.endVersion}")
            }
    }

    /**
     * Two verdicts on the same database, because each catches what the other
     * cannot: Room's own `onValidateSchema` is the literal production check but
     * reports only the first table it dislikes, while the structural diff lists
     * every difference at once, which is what makes a failure here actionable.
     */
    private fun assertSchemaMatchesRoomExpectation(actualConn: Connection, what: String) {
        val expected = openJdbc(newDbFile()).use { expectedConn ->
            createRoomExpectedTables(expectedConn)
            readSchema(expectedConn)
        }
        val differences = diffSchemas(expected, readSchema(actualConn))
        assertEquals("$what: schema differs from the Room expectation", emptyList<String>(), differences)
        assertEquals("$what: Room's own validateMigration rejected the migrated database", "", roomValidationFailure(actualConn))
    }

    /** Runs the generated `onValidateSchema` — the exact code that throws on a real device. */
    private fun roomValidationFailure(conn: Connection): String {
        val delegate = roomOpenDelegate()
        val connectionType = Class.forName("androidx.sqlite.SQLiteConnection")
        val result = delegate.javaClass
            .getMethod("onValidateSchema", connectionType)
            .apply { isAccessible = true }
            .invoke(delegate, jdbcSqliteConnection(conn, connectionType))!!
        // ValidationResult exposes plain public fields, not getters.
        if (result.javaClass.getField("isValid").getBoolean(result)) return ""
        return result.javaClass.getField("expectedFoundMsg").get(result) as? String ?: "validation failed"
    }

    /**
     * Room's `TableInfo` rules, in list form. Notably it compares a DB-side
     * `DEFAULT` only where the `@Entity` declared one — an `ALTER TABLE … ADD
     * COLUMN … DEFAULT 0` leaves a default behind that a fresh `CREATE TABLE`
     * never has, and Room is right not to care. Tables Room does not know about
     * are ignored the same way; a missing one is not.
     */
    private fun diffSchemas(
        expected: Map<String, TableShape>,
        actual: Map<String, TableShape>,
        /**
         * Tolerate columns and indices the expectation does not know about.
         *
         * Only ever true when the EXPECTATION is a historical export: `runMigrations`
         * always walks to the declared version, so comparing the result against
         * (say) 12.json asks "is every table 12 declared still exactly as 12
         * declared it" — and a later purely-additive step must be allowed to have
         * added a column since. The comparison that actually protects production
         * is [assertSchemaMatchesRoomExpectation]'s, whose expectation is Room's
         * own `createAllTables`, and that one stays strict in both directions.
         */
        allowLaterAdditions: Boolean = false,
    ): List<String> = buildList {
        expected.forEach { (table, expectedShape) ->
            val actualShape = actual[table]
            if (actualShape == null) {
                add("table `$table` is missing")
                return@forEach
            }
            (expectedShape.columns.keys + actualShape.columns.keys).sorted().forEach { column ->
                val want = expectedShape.columns[column]
                val got = actualShape.columns[column]
                when {
                    want == null ->
                        if (!allowLaterAdditions) add("`$table`.`$column` exists but no entity declares it")
                    got == null -> add("`$table`.`$column` is missing")
                    else -> {
                        if (want.affinity != got.affinity) add("`$table`.`$column` affinity ${want.affinity} != ${got.affinity}")
                        if (want.notNull != got.notNull) add("`$table`.`$column` notNull ${want.notNull} != ${got.notNull}")
                        if (want.primaryKeyPosition != got.primaryKeyPosition) {
                            add("`$table`.`$column` primary-key position ${want.primaryKeyPosition} != ${got.primaryKeyPosition}")
                        }
                        if (want.defaultValue != null && want.defaultValue != got.defaultValue) {
                            add("`$table`.`$column` default ${want.defaultValue} != ${got.defaultValue}")
                        }
                    }
                }
            }
            (expectedShape.indices.keys + actualShape.indices.keys).sorted().forEach { index ->
                val want = expectedShape.indices[index]
                val got = actualShape.indices[index]
                when {
                    want == null ->
                        if (!allowLaterAdditions) add("`$table` has index `$index` that no entity declares")
                    got == null -> add("`$table` is missing index `$index`")
                    want != got -> add("`$table` index `$index` $want != $got")
                }
            }
        }
    }

    /**
     * The authoritative expectation: the generated `BtDatabase_Impl`'s own
     * `createAllTables`, invoked through a JDBC-backed `SQLiteConnection`.
     */
    private fun createRoomExpectedTables(conn: Connection) {
        val delegate = roomOpenDelegate()
        val connectionType = Class.forName("androidx.sqlite.SQLiteConnection")
        delegate.javaClass
            .getMethod("createAllTables", connectionType)
            .apply { isAccessible = true }
            .invoke(delegate, jdbcSqliteConnection(conn, connectionType))
    }

    private fun roomOpenDelegate(): Any {
        val implClass = Class.forName("at.bettertrack.app.data.db.BtDatabase_Impl")
        val impl = instantiateWithoutConstructor(implClass)
        return implClass.declaredMethods
            .first { it.name == "createOpenDelegate" && it.parameterCount == 0 }
            .apply { isAccessible = true }
            .invoke(impl)!!
    }

    /**
     * `BtDatabase_Impl` is only ever a bag of generated methods here — we call
     * one of them and throw it away — but its `RoomDatabase` supertype does real
     * work in its constructor. Allocating without running it keeps the test
     * independent of whatever `RoomDatabase` initialises today.
     */
    private fun instantiateWithoutConstructor(type: Class<*>): Any =
        runCatching { type.getDeclaredConstructor().apply { isAccessible = true }.newInstance() }
            .getOrElse {
                val unsafeField = Class.forName("sun.misc.Unsafe").getDeclaredField("theUnsafe").apply { isAccessible = true }
                val unsafe = unsafeField.get(null)
                unsafe.javaClass.getMethod("allocateInstance", Class::class.java).invoke(unsafe, type)!!
            }

    // ── JDBC ⇄ androidx.sqlite test doubles ──────────────────────────────────

    /** A [SupportSQLiteDatabase] that is really a JDBC connection. */
    private fun jdbcSupportDatabase(conn: Connection): SupportSQLiteDatabase =
        Proxy.newProxyInstance(
            SupportSQLiteDatabase::class.java.classLoader,
            arrayOf(SupportSQLiteDatabase::class.java),
        ) { _, method, args ->
            when (method.name) {
                "execSQL" -> conn.exec(args!![0] as String)
                "query" -> jdbcCursor(conn, args!![0] as String)
                "toString" -> "jdbc:SupportSQLiteDatabase"
                "hashCode" -> System.identityHashCode(conn)
                "equals" -> false
                else -> error(
                    "SupportSQLiteDatabase.${method.name}() is not implemented by this test double — " +
                        "a migration started using an API the JVM harness cannot execute.",
                )
            }
        } as SupportSQLiteDatabase

    /**
     * `androidx.sqlite.SQLiteConnection` over JDBC. Room's own `execSQL` helper
     * goes through `prepare(…).step()`, so the statement half has to be real
     * enough to run a PRAGMA and read its rows back.
     */
    private fun jdbcSqliteConnection(conn: Connection, connectionType: Class<*>): Any =
        Proxy.newProxyInstance(connectionType.classLoader, arrayOf(connectionType)) { _, method, args ->
            when (method.name) {
                "execSQL" -> conn.exec(args!![0] as String)
                "prepare" -> jdbcSqliteStatement(conn, args!![0] as String)
                "close" -> null
                "toString" -> "jdbc:SQLiteConnection"
                "hashCode" -> System.identityHashCode(conn)
                "equals" -> false
                else -> error("SQLiteConnection.${method.name}() is not implemented by this test double")
            }
        }

    /** `androidx.sqlite.SQLiteStatement` over JDBC — 0-based reads, as androidx defines them. */
    private fun jdbcSqliteStatement(conn: Connection, sql: String): Any {
        val statementType = Class.forName("androidx.sqlite.SQLiteStatement")
        val statement = conn.createStatement()
        var rs: java.sql.ResultSet? = null
        var names: List<String> = emptyList()
        return Proxy.newProxyInstance(statementType.classLoader, arrayOf(statementType)) { _, method, args ->
            fun index() = (args!![0] as Int) + 1
            when (method.name) {
                "step" -> {
                    if (rs == null) {
                        val hasResults = statement.execute(sql)
                        if (hasResults) {
                            rs = statement.resultSet
                            names = rs!!.metaData.let { md -> (1..md.columnCount).map { md.getColumnName(it) } }
                        }
                    }
                    rs?.next() ?: false
                }
                "getColumnCount" -> names.size
                "getColumnName" -> names[args!![0] as Int]
                "getColumnNames" -> names
                "getText" -> rs!!.getString(index()).orEmpty()
                "getLong" -> rs!!.getLong(index())
                "getDouble" -> rs!!.getDouble(index())
                "getBlob" -> rs!!.getBytes(index()) ?: ByteArray(0)
                "isNull" -> rs!!.getObject(index()) == null
                "getColumnType" -> when (rs!!.getObject(index())) {
                    null -> 5 // SQLITE_NULL
                    is Int, is Long -> 1 // SQLITE_INTEGER
                    is Double, is Float -> 2 // SQLITE_FLOAT
                    is ByteArray -> 4 // SQLITE_BLOB
                    else -> 3 // SQLITE_TEXT
                }
                "reset", "clearBindings" -> null
                "close" -> { rs?.close(); statement.close(); null }
                "toString" -> "jdbc:SQLiteStatement"
                "hashCode" -> System.identityHashCode(statement)
                "equals" -> false
                else -> error("SQLiteStatement.${method.name}() is not implemented by this test double")
            }
        }
    }

    /** Android's [Cursor] over a JDBC `ResultSet` — the columns Room's PRAGMA reads need. */
    private fun jdbcCursor(conn: Connection, sql: String): Cursor {
        val statement = conn.createStatement()
        val rs = statement.executeQuery(sql)
        val names = rs.metaData.let { md -> (1..md.columnCount).map { md.getColumnName(it) } }
        return Proxy.newProxyInstance(Cursor::class.java.classLoader, arrayOf(Cursor::class.java)) { _, method, args ->
            when (method.name) {
                "getColumnIndex" -> names.indexOf(args!![0] as String)
                "getColumnCount" -> names.size
                "getColumnName" -> names[args!![0] as Int]
                "moveToNext" -> rs.next()
                "getString" -> rs.getString((args!![0] as Int) + 1)
                "getInt" -> rs.getInt((args!![0] as Int) + 1)
                "getLong" -> rs.getLong((args!![0] as Int) + 1)
                "isNull" -> rs.getObject((args!![0] as Int) + 1) == null
                "close" -> { rs.close(); statement.close(); null }
                "toString" -> "jdbc:Cursor"
                "hashCode" -> System.identityHashCode(rs)
                "equals" -> false
                else -> error("Cursor.${method.name}() is not implemented by this test double")
            }
        } as Cursor
    }

    // ── Room's TableInfo comparison, reimplemented over PRAGMA ───────────────

    private data class ColumnShape(
        val affinity: String,
        val notNull: Boolean,
        val primaryKeyPosition: Int,
        val defaultValue: String?,
    )

    private data class IndexShape(val unique: Boolean, val columns: List<String>)

    private data class TableShape(
        val columns: Map<String, ColumnShape>,
        val indices: Map<String, IndexShape>,
    )

    /** Builds a scratch database from [statements] purely to read its shape. */
    private fun schemaFrom(statements: List<String>): Map<String, TableShape> =
        openJdbc(newDbFile()).use { conn ->
            conn.applyAll(statements)
            readSchema(conn)
        }

    private fun readSchema(conn: Connection): Map<String, TableShape> {
        val tables = conn.list(
            "SELECT name FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%' " +
                "AND name NOT IN ('room_master_table', 'android_metadata')",
        )
        return tables.associateWith { table ->
            val columns = mutableMapOf<String, ColumnShape>()
            conn.createStatement().use { st ->
                st.executeQuery("PRAGMA table_info(`$table`)").use { rs ->
                    while (rs.next()) {
                        columns[rs.getString("name")] = ColumnShape(
                            affinity = affinityOf(rs.getString("type")),
                            notNull = rs.getInt("notnull") != 0,
                            primaryKeyPosition = rs.getInt("pk"),
                            defaultValue = rs.getString("dflt_value"),
                        )
                    }
                }
            }
            val indices = mutableMapOf<String, IndexShape>()
            val indexRows = mutableListOf<Pair<String, Boolean>>()
            conn.createStatement().use { st ->
                st.executeQuery("PRAGMA index_list(`$table`)").use { rs ->
                    // Room reads only the indices it could have created itself.
                    while (rs.next()) {
                        val name = rs.getString("name")
                        if (name.startsWith("index_")) indexRows += name to (rs.getInt("unique") != 0)
                    }
                }
            }
            indexRows.forEach { (name, unique) ->
                indices[name] = IndexShape(unique, conn.list("PRAGMA index_info(`$name`)", column = "name"))
            }
            TableShape(columns, indices)
        }
    }

    /**
     * Room compares a column's type AFFINITY, and its default value only when the
     * `@Entity` declared one — so the shapes are normalised the same way before
     * they are compared. See `androidx.room.util.TableInfo`.
     */
    private fun affinityOf(declaredType: String?): String {
        val type = declaredType?.uppercase().orEmpty()
        return when {
            type.isEmpty() -> "BLOB"
            type.contains("INT") -> "INTEGER"
            type.contains("CHAR") || type.contains("CLOB") || type.contains("TEXT") -> "TEXT"
            type.contains("BLOB") -> "BLOB"
            type.contains("REAL") || type.contains("FLOA") || type.contains("DOUB") -> "REAL"
            else -> "NUMERIC"
        }
    }

    // ── Tiny JDBC helpers ────────────────────────────────────────────────────

    private fun newDbFile(): File =
        File(Files.createTempDirectory("bt-migration").toFile(), "bettertrack.db").also { it.deleteOnExit() }

    private fun openJdbc(file: File): Connection = DriverManager.getConnection("jdbc:sqlite:${file.absolutePath}")

    private fun Connection.exec(sql: String): Any? {
        createStatement().use { it.execute(sql) }
        return null
    }

    private fun Connection.applyAll(statements: List<String>) = statements.forEach { exec(it) }

    private fun Connection.userVersion(): Int =
        createStatement().use { st ->
            st.executeQuery("PRAGMA user_version").use { it.next(); it.getInt(1) }
        }

    private fun Connection.list(sql: String, column: String = "name"): List<String> =
        createStatement().use { st ->
            st.executeQuery(sql).use { rs ->
                buildList { while (rs.next()) add(rs.getString(column)) }
            }
        }

    private fun Connection.single(sql: String): String? =
        createStatement().use { st -> st.executeQuery(sql).use { if (it.next()) it.getString(1) else null } }

    private fun Connection.rowCounts(tables: List<String>): Map<String, Int> =
        tables.associateWith { table ->
            createStatement().use { st ->
                st.executeQuery("SELECT COUNT(*) FROM `$table`").use { it.next(); it.getInt(1) }
            }
        }

