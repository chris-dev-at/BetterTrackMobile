    /** …and it must arrive there with every row still in it. */
    @Test
    fun ownersRealV7DeviceKeepsItsRowsAcrossTheMigration() {
        val db = newDbFile()
        openJdbc(db).use { conn ->
            conn.applyAll(SCHEMA_V7_OWNER_DEVICE)
            conn.exec("PRAGMA user_version = 7")
            conn.applyAll(SAMPLE_ROWS_V7)
